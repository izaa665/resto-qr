-- 1. TABEL PENGGUNA SISTEM (USERS / ROLES)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE,
    role TEXT NOT NULL CHECK (role IN ('admin', 'kasir', 'dapur')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL PENGATURAN RESTORAN
CREATE TABLE IF NOT EXISTS restaurant_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Rasa Nusantara Resto & Cafe',
    address TEXT DEFAULT 'Jl. Kuliner Lezat No. 88, Jakarta',
    phone TEXT DEFAULT '0812-3456-7890',
    wifi_password TEXT DEFAULT 'nusantara88',
    tax_percent INT DEFAULT 0
);

-- 3. TABEL KATEGORI MAKANAN & MINUMAN
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    icon TEXT DEFAULT 'utensils'
);

-- 4. TABEL PRODUK (MAKANAN & MINUMAN)
CREATE TABLE IF NOT EXISTS menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    description TEXT,
    price INT NOT NULL,
    image TEXT,
    is_available BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABEL MEJA RESTORAN & KODE QR UNIK
CREATE TABLE IF NOT EXISTS restaurant_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INT UNIQUE NOT NULL,
    table_code TEXT UNIQUE NOT NULL,
    qr_token TEXT UNIQUE NOT NULL,
    description TEXT DEFAULT ''
);

-- 6. TABEL PESANAN (ORDERS - DINE IN / TAKEAWAY)
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    order_type TEXT NOT NULL DEFAULT 'dine_in' CHECK (order_type IN ('dine_in', 'takeaway')),
    table_number INT,
    customer_name TEXT NOT NULL,
    total_amount INT NOT NULL,
    payment_method TEXT NOT NULL,
    payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'waiting_confirmation', 'paid', 'failed', 'refunded')),
    order_status TEXT NOT NULL DEFAULT 'pending' CHECK (order_status IN ('pending', 'processing', 'ready', 'completed', 'cancelled')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. TABEL RINCIAN PESANAN (ORDER ITEMS)
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    menu_id BIGINT REFERENCES menus(id) ON DELETE SET NULL,
    menu_name TEXT NOT NULL,
    price INT NOT NULL,
    qty INT NOT NULL,
    subtotal INT NOT NULL,
    item_notes TEXT
);

-- 8. TABEL RIWAYAT LOG STATUS PESANAN (ORDER STATUS LOGS)
CREATE TABLE IF NOT EXISTS order_status_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status_from TEXT,
    status_to TEXT NOT NULL,
    changed_by TEXT DEFAULT 'Sistem',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. TABEL PENGELUARAN & PEMBELIAN TOKO (EXPENSES)
CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    amount INT NOT NULL,
    expense_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- ROW LEVEL SECURITY (RLS) & PUBLIC ACCESS
-- =========================================================================
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE restaurant_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE menus ENABLE ROW LEVEL SECURITY;
ALTER TABLE restaurant_tables ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_status_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE expenses ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public full access users" ON users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access restaurant_settings" ON restaurant_settings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access categories" ON categories FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access menus" ON menus FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access restaurant_tables" ON restaurant_tables FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access orders" ON orders FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access order_items" ON order_items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access order_status_logs" ON order_status_logs FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access expenses" ON expenses FOR ALL USING (true) WITH CHECK (true);

-- =========================================================================
-- AKTIFKAN SUPABASE REALTIME (KASIR, DAPUR & PELANGGAN AUTO-UPDATE)
-- =========================================================================
